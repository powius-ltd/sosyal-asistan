#!/usr/bin/env node
/**
 * Lokal Supabase şemasından TypeScript tiplerini üretir → src/lib/supabase/database.types.ts.
 * `npm run db:types` (önce `npm run db:start`).
 *
 * `supabase gen types ... > dosya` yerine bu betik: üretim başarısız olursa mevcut dosyayı bozmaz
 * (kabuk yönlendirmesi hata durumunda boş dosya bırakırdı).
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const OUT = resolve(ROOT, "src/lib/supabase/database.types.ts");
const HEADER =
  "// @generated by scripts/db-types.mjs (supabase gen types) — ELLE DÜZENLEME.\n" +
  "// Şema değişince: npm run db:types (lokal Supabase açık olmalı).\n";

// Sabit komut (kullanıcı girdisi yok); Windows'ta npx.cmd için shell gerekir.
const result = spawnSync("npx -y supabase@2.118.0 gen types typescript --local --schema public", {
  cwd: ROOT,
  encoding: "utf8",
  shell: true,
  maxBuffer: 64 * 1024 * 1024,
});

if (result.status !== 0 || !result.stdout.includes("export type Database")) {
  console.error("db:types — tip üretimi başarısız (lokal Supabase açık mı? `npm run db:start`).");
  if (result.stderr) console.error(result.stderr.trim());
  process.exit(1);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, HEADER + result.stdout, "utf8");
console.log(`db:types — yazıldı: src/lib/supabase/database.types.ts (${result.stdout.split("\n").length} satır)`);
